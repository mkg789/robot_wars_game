import type {
  ElectricalCatalogueCategory,
  ElectricalCatalogueItem,
  ElectricalComponentKind,
  ElectricalConnectorCategory,
  ElectricalConnectorSpec,
  ElectricalInterfaceSpec,
  ElectricalPinSpec,
  ElectricalProvenance,
  ElectricalSignalType,
} from "../types/electrical.types";

const datasheetProv = (source: string, notes?: string): ElectricalProvenance => ({
  method: "datasheet",
  verified: true,
  source,
  notes,
});

const estimatedProv = (basis: string, notes?: string): ElectricalProvenance => ({
  method: "estimated",
  basis,
  notes,
});

const unknownProv = (notes: string): ElectricalProvenance => ({
  method: "unknown",
  notes,
});

function makeGroundPair(
  prefix: string,
  prov: ElectricalProvenance,
  connectorId?: string
): { pin: ElectricalPinSpec; iface: ElectricalInterfaceSpec } {
  const pinId = `${prefix}-gnd-pin`;
  return {
    pin: {
      pinId,
      pinName: "GND",
      pinNumber: "GND",
      pinType: "ground",
      role: "ground",
      direction: "reference",
      signalTypes: [],
      isGround: true,
      connectorId,
      provenance: prov,
    },
    iface: {
      interfaceId: `${prefix}-gnd`,
      name: "Ground Reference (GND)",
      role: "ground",
      pinIds: [pinId],
      connectorId,
      provenance: prov,
    },
  };
}

function makeSimpleConnector(
  connectorId: string,
  connectorType: ElectricalConnectorCategory,
  name: string,
  pins: readonly ElectricalPinSpec[],
  prov: ElectricalProvenance,
  ratedCurrentA?: number
): ElectricalConnectorSpec {
  return {
    connectorId,
    connectorType,
    name,
    pinCount: pins.length,
    pinDefinitions: pins.map((p, idx) => ({
      pinNumber: p.pinNumber ?? idx + 1,
      pinId: p.pinId,
      label: p.pinName,
    })),
    ratedCurrentA,
    provenance: prov,
  };
}

interface SensorBlueprint {
  id: string;
  name: string;
  description: string;
  vMin: number;
  vMax: number;
  vNom: number;
  typCurrentA?: number;
  signals: readonly ElectricalSignalType[];
  signalNames: readonly string[];
  dims?: { length: number; height: number; width: number };
  massKg?: number;
  color?: string;
  datasheetUrl?: string;
  prov: ElectricalProvenance;
  unknownFields?: readonly string[];
  assumptions?: readonly string[];
}

function makeSensorItem(bp: SensorBlueprint): ElectricalCatalogueItem {
  const connId = `${bp.id}-hdr`;
  const vccPin: ElectricalPinSpec = {
    pinId: `${bp.id}-vcc-pin`,
    pinName: "VCC",
    pinNumber: 1,
    pinType: "power",
    role: "power-input",
    direction: "input",
    supportedVoltage: { nominalV: bp.vNom, minV: bp.vMin, maxV: bp.vMax },
    currentLimits: bp.typCurrentA !== undefined ? { nominalA: bp.typCurrentA } : undefined,
    signalTypes: [],
    isPower: true,
    connectorId: connId,
    provenance: bp.prov,
  };
  const { pin: gndPin, iface: gndIface } = makeGroundPair(bp.id, bp.prov, connId);
  const sigPins: ElectricalPinSpec[] = bp.signalNames.map((sigName, idx) => ({
    pinId: `${bp.id}-sig-${idx}`,
    pinName: sigName,
    pinNumber: idx + 2,
    pinType: "signal",
    role: bp.signals.some((s) => s === "i2c" || s === "spi" || s === "uart")
      ? "signal-bidirectional"
      : "signal-output",
    direction: bp.signals.some((s) => s === "i2c" || s === "spi" || s === "uart")
      ? "bidirectional"
      : "output",
    supportedVoltage: { nominalV: bp.vNom, minV: 0, maxV: bp.vMax },
    signalTypes: bp.signals,
    digitalCapable: bp.signals.includes("digital") || bp.signals.includes("pwm"),
    analogCapable: bp.signals.includes("analog"),
    pwmCapable: bp.signals.includes("pwm"),
    communicationCapabilities: bp.signals,
    connectorId: connId,
    provenance: bp.prov,
  }));

  const allPins = [vccPin, ...sigPins, gndPin];
  const connector = makeSimpleConnector(connId, "pin-header", "Sensor Header", allPins, bp.prov);

  const interfaces: ElectricalInterfaceSpec[] = [
    {
      interfaceId: `${bp.id}-pwr-in`,
      name: "Sensor Power (VCC)",
      role: "power-input",
      voltageSpec: { nominalV: bp.vNom, minV: bp.vMin, maxV: bp.vMax },
      currentSpec: bp.typCurrentA !== undefined ? { nominalA: bp.typCurrentA } : undefined,
      pinIds: [vccPin.pinId],
      connectorId: connId,
      groundReferenceInterfaceId: gndIface.interfaceId,
      provenance: bp.prov,
    },
    {
      interfaceId: `${bp.id}-sig-out`,
      name: `Sensor Interface (${bp.signalNames.join("/")})`,
      role: sigPins[0]?.role ?? "signal-output",
      voltageSpec: { nominalV: bp.vNom, maxV: bp.vMax, logicLevelV: bp.vNom },
      supportedSignals: bp.signals,
      pinIds: sigPins.map((p) => p.pinId),
      connectorId: connId,
      groundReferenceInterfaceId: gndIface.interfaceId,
      provenance: bp.prov,
    },
    gndIface,
  ];

  const dims = bp.dims ?? { length: 0.032, height: 0.012, width: 0.022 };
  const unknownFields = bp.unknownFields ?? (bp.typCurrentA === undefined ? ["nominalCurrentA"] : []);

  return {
    id: bp.id,
    name: bp.name,
    category: "sensors",
    description: bp.description,
    componentType: "sensor",
    partType: "Structural Block",
    dimensions: dims,
    massKg: bp.massKg ?? 0.012,
    color: bp.color ?? "#0284c7",
    mechanicalMountCategory: "plate-mount",
    datasheetUrl: bp.datasheetUrl,
    provenance: bp.prov,
    assumptions: bp.assumptions ?? [],
    electricalSpecTemplate: {
      componentType: "sensor",
      model: bp.name,
      interfaces,
      pins: allPins,
      connectors: [connector],
      assumptions: bp.assumptions ?? [],
      unknownFields,
      provenance: bp.prov,
    },
  };
}

interface BatteryBlueprint {
  id: string;
  name: string;
  description: string;
  nomV: number;
  minV: number;
  maxV: number;
  capacityMah?: number;
  contDischargeA?: number;
  peakDischargeA?: number;
  chemistry: string;
  cellCountS?: number;
  connectorType: ElectricalConnectorCategory;
  dims: { length: number; height: number; width: number };
  massKg: number;
  color: string;
  prov: ElectricalProvenance;
  unknownFields: readonly string[];
  assumptions: readonly string[];
}

function makeBatteryItem(bp: BatteryBlueprint): ElectricalCatalogueItem {
  const connId = `${bp.id}-conn`;
  const posPin: ElectricalPinSpec = {
    pinId: "pin-bat-pos",
    pinName: "BAT+",
    pinNumber: 1,
    pinType: "power",
    role: "power-output",
    direction: "output",
    supportedVoltage: { nominalV: bp.nomV, minV: bp.minV, maxV: bp.maxV },
    currentLimits: { maxContinuousA: bp.contDischargeA, peakOrStallA: bp.peakDischargeA },
    signalTypes: [],
    isPower: true,
    connectorId: connId,
    provenance: bp.prov,
  };
  const negPin: ElectricalPinSpec = {
    pinId: "pin-bat-neg",
    pinName: "BAT- (GND)",
    pinNumber: 2,
    pinType: "ground",
    role: "ground",
    direction: "reference",
    signalTypes: [],
    isGround: true,
    connectorId: connId,
    provenance: bp.prov,
  };
  const conn = makeSimpleConnector(connId, bp.connectorType, `${bp.connectorType.toUpperCase()} Lead`, [posPin, negPin], bp.prov, bp.contDischargeA);

  return {
    id: bp.id,
    name: bp.name,
    category: "power",
    description: bp.description,
    componentType: "battery",
    partType: "Battery",
    dimensions: bp.dims,
    massKg: bp.massKg,
    color: bp.color,
    mechanicalMountCategory: "foundation-deck",
    provenance: bp.prov,
    assumptions: bp.assumptions,
    electricalSpecTemplate: {
      componentType: "battery",
      model: bp.name,
      interfaces: [
        {
          interfaceId: "bat-power-out",
          name: "Main DC Power Output (+)",
          role: "power-output",
          voltageSpec: { nominalV: bp.nomV, minV: bp.minV, maxV: bp.maxV },
          currentSpec: { maxContinuousA: bp.contDischargeA, peakOrStallA: bp.peakDischargeA },
          pinIds: ["pin-bat-pos"],
          connectorId: connId,
          groundReferenceInterfaceId: "bat-gnd",
          provenance: bp.prov,
        },
        {
          interfaceId: "bat-gnd",
          name: "Battery Negative / Reference (-)",
          role: "ground",
          pinIds: ["pin-bat-neg"],
          connectorId: connId,
          provenance: bp.prov,
        },
      ],
      pins: [posPin, negPin],
      connectors: [conn],
      batterySpec: {
        nominalVoltageV: bp.nomV,
        minOperatingVoltageV: bp.minV,
        maxVoltageV: bp.maxV,
        capacityMah: bp.capacityMah,
        maxContinuousDischargeA: bp.contDischargeA,
        peakDischargeA: bp.peakDischargeA,
        chemistry: bp.chemistry,
        cellCountS: bp.cellCountS,
      },
      assumptions: bp.assumptions,
      unknownFields: bp.unknownFields,
      provenance: bp.prov,
    },
  };
}

interface RegulatorBlueprint {
  id: string;
  name: string;
  description: string;
  componentType: ElectricalComponentKind;
  inMinV: number;
  inMaxV: number;
  outNomV: number;
  outMinV: number;
  outMaxV: number;
  maxContA: number;
  powerRole: "buck" | "boost" | "linear";
  efficiency?: number;
  dropoutVoltageV?: number;
  quiescentA?: number;
  datasheetUrl?: string;
  prov: ElectricalProvenance;
  assumptions: readonly string[];
}

function makeRegulatorItem(bp: RegulatorBlueprint): ElectricalCatalogueItem {
  const inConnId = `${bp.id}-in-conn`;
  const outConnId = `${bp.id}-out-conn`;
  const vinPin: ElectricalPinSpec = {
    pinId: `${bp.id}-vin-pin`,
    pinName: "VIN+",
    pinNumber: 1,
    pinType: "power",
    role: "power-input",
    direction: "input",
    supportedVoltage: { minV: bp.inMinV, nominalV: (bp.inMinV + bp.inMaxV) / 2, maxV: bp.inMaxV },
    signalTypes: [],
    isPower: true,
    connectorId: inConnId,
    provenance: bp.prov,
  };
  const voutPin: ElectricalPinSpec = {
    pinId: `${bp.id}-vout-pin`,
    pinName: `VOUT (${bp.outNomV}V)`,
    pinNumber: 2,
    pinType: "power",
    role: "power-output",
    direction: "output",
    supportedVoltage: { minV: bp.outMinV, nominalV: bp.outNomV, maxV: bp.outMaxV },
    currentLimits: { maxContinuousA: bp.maxContA },
    signalTypes: [],
    isPower: true,
    connectorId: outConnId,
    provenance: bp.prov,
  };
  const { pin: gndPin, iface: gndIface } = makeGroundPair(bp.id, bp.prov, inConnId);

  return {
    id: bp.id,
    name: bp.name,
    category: "power",
    description: bp.description,
    componentType: bp.componentType,
    partType: "Structural Block",
    dimensions: { length: 0.044, height: 0.014, width: 0.024 },
    massKg: 0.018,
    color: "#15803d",
    mechanicalMountCategory: "plate-mount",
    datasheetUrl: bp.datasheetUrl,
    provenance: bp.prov,
    assumptions: bp.assumptions,
    electricalSpecTemplate: {
      componentType: bp.componentType,
      model: bp.name,
      interfaces: [
        {
          interfaceId: `${bp.id}-pwr-in`,
          name: "Regulator VIN",
          role: "power-input",
          voltageSpec: { minV: bp.inMinV, maxV: bp.inMaxV },
          pinIds: [vinPin.pinId],
          connectorId: inConnId,
          groundReferenceInterfaceId: gndIface.interfaceId,
          provenance: bp.prov,
        },
        {
          interfaceId: `${bp.id}-pwr-out`,
          name: `Regulated ${bp.outNomV}V Output`,
          role: "power-output",
          voltageSpec: { nominalV: bp.outNomV, minV: bp.outMinV, maxV: bp.outMaxV },
          currentSpec: { maxContinuousA: bp.maxContA },
          pinIds: [voutPin.pinId],
          connectorId: outConnId,
          groundReferenceInterfaceId: gndIface.interfaceId,
          provenance: bp.prov,
        },
        gndIface,
      ],
      pins: [vinPin, voutPin, gndPin],
      connectors: [
        makeSimpleConnector(inConnId, "screw-terminal", "Input Terminal", [vinPin, gndPin], bp.prov),
        makeSimpleConnector(outConnId, "pin-header", "Output Header", [voutPin, gndPin], bp.prov),
      ],
      driverOrRegulatorSpec: {
        powerRole: bp.powerRole,
        inputVoltageRangeV: { minV: bp.inMinV, maxV: bp.inMaxV },
        outputVoltageRangeV: { minV: bp.outMinV, maxV: bp.outMaxV },
        continuousCurrentPerChannelA: bp.maxContA,
        efficiency: bp.efficiency,
        dropoutVoltageV: bp.dropoutVoltageV,
        quiescentCurrentA: bp.quiescentA,
        efficiencyProvenance:
          bp.efficiency !== undefined
            ? estimatedProv("Typical datasheet/converter nominal efficiency assumption")
            : undefined,
      },
      assumptions: bp.assumptions,
      unknownFields: bp.quiescentA === undefined ? ["quiescentCurrentA", "thermalDeratingCurve"] : [],
      provenance: bp.prov,
    },
  };
}

interface ControllerBlueprint {
  id: string;
  name: string;
  description: string;
  boardArchitecture: string;
  logicV: number;
  vinMinV: number;
  vinMaxV: number;
  maxRailA: number;
  pwmCount: number;
  adcCount: number;
  digitalCount: number;
  protocols: readonly ElectricalSignalType[];
  powerConnector: ElectricalConnectorCategory;
  dims: { length: number; height: number; width: number };
  massKg: number;
  color: string;
  datasheetUrl: string;
  prov: ElectricalProvenance;
}

function makeControllerItem(bp: ControllerBlueprint): ElectricalCatalogueItem {
  const pwrConnId = `${bp.id}-pwr-conn`;
  const hdrConnId = `${bp.id}-hdr-conn`;

  const vinPin: ElectricalPinSpec = {
    pinId: "pin-vin",
    pinName: "VIN",
    pinNumber: "VIN",
    pinType: "power",
    role: "power-input",
    direction: "input",
    supportedVoltage: { nominalV: bp.vinMinV, minV: bp.vinMinV, maxV: bp.vinMaxV },
    signalTypes: [],
    isPower: true,
    connectorId: pwrConnId,
    provenance: bp.prov,
  };
  const vccPin: ElectricalPinSpec = {
    pinId: "pin-vcc",
    pinName: `${bp.logicV}V Logic Out`,
    pinNumber: "VCC",
    pinType: "power",
    role: "power-output",
    direction: "output",
    supportedVoltage: {
      nominalV: bp.logicV,
      minV: Number((bp.logicV * 0.95).toFixed(2)),
      maxV: Number((bp.logicV * 1.05).toFixed(2)),
      logicLevelV: bp.logicV,
    },
    currentLimits: { maxContinuousA: bp.maxRailA },
    signalTypes: [],
    isPower: true,
    connectorId: hdrConnId,
    provenance: bp.prov,
  };
  const { pin: gndPin, iface: gndIface } = makeGroundPair(bp.id, bp.prov, pwrConnId);

  const pwmPins: ElectricalPinSpec[] = Array.from({ length: Math.min(bp.pwmCount, 4) }, (_, i) => ({
    pinId: `pin-pwm-${i}`,
    pinName: `PWM${i + 1}`,
    pinNumber: `D${i + 3}`,
    pinType: "signal",
    role: "signal-bidirectional",
    direction: "bidirectional",
    supportedVoltage: { nominalV: bp.logicV, minV: 0, maxV: bp.logicV, logicLevelV: bp.logicV },
    signalTypes: ["digital", "pwm"],
    digitalCapable: true,
    pwmCapable: true,
    analogCapable: false,
    connectorId: hdrConnId,
    constraints: [`Logic level ${bp.logicV}V max; do not drive motors directly`],
    provenance: bp.prov,
  }));

  const adcPins: ElectricalPinSpec[] = Array.from({ length: Math.min(bp.adcCount, 2) }, (_, i) => ({
    pinId: `pin-adc-${i}`,
    pinName: `ADC${i}`,
    pinNumber: `A${i}`,
    pinType: "signal",
    role: "signal-input",
    direction: "input",
    supportedVoltage: { nominalV: bp.logicV, minV: 0, maxV: bp.logicV, logicLevelV: bp.logicV },
    signalTypes: ["analog", "digital"],
    digitalCapable: true,
    analogCapable: true,
    pwmCapable: false,
    connectorId: hdrConnId,
    provenance: bp.prov,
  }));

  const busPin: ElectricalPinSpec = {
    pinId: "pin-comm-bus",
    pinName: `Bus (${bp.protocols.slice(0, 3).map((s) => s.toUpperCase()).join("/")})`,
    pinNumber: "BUS",
    pinType: "signal",
    role: "signal-bidirectional",
    direction: "bidirectional",
    supportedVoltage: { nominalV: bp.logicV, minV: 0, maxV: bp.logicV, logicLevelV: bp.logicV },
    signalTypes: bp.protocols,
    digitalCapable: true,
    communicationCapabilities: bp.protocols,
    connectorId: hdrConnId,
    provenance: bp.prov,
  };

  const allPins = [vinPin, vccPin, gndPin, ...pwmPins, ...adcPins, busPin];

  return {
    id: bp.id,
    name: bp.name,
    category: "controllers",
    description: bp.description,
    componentType: "controller",
    partType: "Controller",
    dimensions: bp.dims,
    massKg: bp.massKg,
    color: bp.color,
    mechanicalMountCategory: "foundation-deck",
    datasheetUrl: bp.datasheetUrl,
    provenance: bp.prov,
    assumptions: ["Representative GPIO subset exposed for schematic wiring."],
    electricalSpecTemplate: {
      componentType: "controller",
      model: bp.name,
      interfaces: [
        {
          interfaceId: "ctrl-power-in",
          name: "Controller Power Input (VIN)",
          role: "power-input",
          voltageSpec: { nominalV: bp.vinMinV, minV: bp.vinMinV, maxV: bp.vinMaxV },
          pinIds: ["pin-vin"],
          connectorId: pwrConnId,
          groundReferenceInterfaceId: gndIface.interfaceId,
          provenance: bp.prov,
        },
        {
          interfaceId: "ctrl-logic-vcc",
          name: `${bp.logicV}V Logic Rail`,
          role: "power-output",
          voltageSpec: {
            nominalV: bp.logicV,
            minV: Number((bp.logicV * 0.95).toFixed(2)),
            maxV: Number((bp.logicV * 1.05).toFixed(2)),
            logicLevelV: bp.logicV,
          },
          currentSpec: { maxContinuousA: bp.maxRailA },
          pinIds: ["pin-vcc"],
          connectorId: hdrConnId,
          groundReferenceInterfaceId: gndIface.interfaceId,
          provenance: bp.prov,
        },
        gndIface,
        {
          interfaceId: "ctrl-gpio-signals",
          name: "GPIO / PWM / Bus Signals",
          role: "signal-bidirectional",
          voltageSpec: { nominalV: bp.logicV, maxV: bp.logicV, logicLevelV: bp.logicV },
          supportedSignals: ["digital", "pwm", "analog", ...bp.protocols],
          pinIds: [...pwmPins, ...adcPins, busPin].map((p) => p.pinId),
          connectorId: hdrConnId,
          groundReferenceInterfaceId: gndIface.interfaceId,
          provenance: bp.prov,
        },
      ],
      pins: allPins,
      connectors: [
        makeSimpleConnector(pwrConnId, bp.powerConnector, "Board Power Supply", [vinPin, gndPin], bp.prov),
        makeSimpleConnector(hdrConnId, "pin-header", "GPIO Pin Header", [vccPin, ...pwmPins, ...adcPins, busPin], bp.prov),
      ],
      controllerSpec: {
        boardArchitecture: bp.boardArchitecture,
        logicLevelV: bp.logicV,
        inputVoltageRangeV: { minV: bp.vinMinV, maxV: bp.vinMaxV },
        maxLogicRailCurrentA: bp.maxRailA,
        gpioCount: bp.digitalCount,
        digitalPinCount: bp.digitalCount,
        analogPinCount: bp.adcCount,
        pwmPinCount: bp.pwmCount,
        communicationProtocols: bp.protocols,
      },
      assumptions: ["Representative GPIO subset modeled; hardware peripheral multiplexing omitted."],
      unknownFields: ["idleCurrentA"],
      provenance: bp.prov,
    },
  };
}

